#!/usr/bin/env python3
"""Turns the WANDS dataset into a bench fixture and a relevance query set (Sprint 3).

WANDS (Wayfair ANnotation DataSet, MIT license, https://github.com/wayfair/WANDS) has 42,994 products, 480 real
search queries and 233,448 human labels graded Exact, Partial or Irrelevant. This script reads its three
tab-separated files and writes:

  wands.sql      resets the bench catalog and loads every WANDS product (product id = WANDS id + 1)
  queries.json   each query with its split (tune or heldout) and graded labels keyed by catalog product id
  manifest.json  counts, mapping rules and the SHA-256 of wands.sql

Mapping. name = product_name, description = product_description (empty when missing), category = the first
product_class ("Uncategorized" when missing). WANDS has no prices, so each product gets a deterministic synthetic
price, log-uniform between $5 and $2,000, from a hash of its id. Stock is 100 for every product.

Split. Queries are shuffled with --split-seed and the first 60% become the tuning set. Decide on the split before
looking at any engine's results, and score the held-out set only after the configurations are frozen.

Standard library only. Run it with `python3 -I`, because it reads downloaded files.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import random
from pathlib import Path

FIXTURE_VERSION = 1
BATCH_SIZE = 500
GAINS = {"Exact": 2, "Partial": 1, "Irrelevant": 0}
MIN_CENTS, MAX_CENTS = 500, 200_000
TUNE_SHARE = 0.6


def sql_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def batched_insert(table: str, columns: list[str], rows: list[list[str]]) -> list[str]:
    statements = []
    for start in range(0, len(rows), BATCH_SIZE):
        values = ",\n".join("(" + ", ".join(row) + ")" for row in rows[start:start + BATCH_SIZE])
        statements.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values};")
    return statements


def price_cents(wands_id: int) -> int:
    digest = hashlib.sha256(f"wands-price:{wands_id}".encode()).digest()
    unit = int.from_bytes(digest[:8], "big") / 2**64
    return round(math.exp(math.log(MIN_CENTS) + unit * (math.log(MAX_CENTS) - math.log(MIN_CENTS))))


def read_tsv(path: Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw-dir", required=True, type=Path, help="directory with product.csv, query.csv, label.csv")
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--split-seed", type=int, default=20261109)
    args = parser.parse_args()
    csv.field_size_limit(1 << 30)

    products = read_tsv(args.raw_dir / "product.csv")
    queries = read_tsv(args.raw_dir / "query.csv")
    labels = read_tsv(args.raw_dir / "label.csv")

    def category_of(row: dict[str, str]) -> str:
        first = (row.get("product_class") or "").split("|")[0].strip()
        return first or "Uncategorized"

    category_names = sorted({category_of(p) for p in products})
    category_ids = {name: cid for cid, name in enumerate(category_names, start=1)}

    category_rows = [[str(cid), sql_str(name[:255]), sql_str(f"WANDS product class: {name}"[:255]),
                      sql_str(f"https://images.shopsphere.test/wands/categories/{cid}.jpg")]
                     for name, cid in category_ids.items()]
    product_rows = []
    for row in sorted(products, key=lambda r: int(r["product_id"])):
        wands_id = int(row["product_id"])
        cents = price_cents(wands_id)
        product_rows.append([
            str(wands_id + 1),
            sql_str(row["product_name"].strip()),
            sql_str(f"https://images.shopsphere.test/wands/{wands_id}.jpg"),
            f"{cents / 100:.2f}",
            str(cents),
            sql_str((row.get("product_description") or "").strip()),
            str(category_ids[category_of(row)]),
            "100",
        ])

    statements = [
        f"-- WANDS bench fixture v{FIXTURE_VERSION}. Generated by benchmarks/seed/load_wands.py; do not edit.",
        "SET FOREIGN_KEY_CHECKS = 0;",
        *(f"TRUNCATE TABLE {t};" for t in ("orderitems", "orders", "cart", "wishlist", "processed_stripe_events",
                                           "search_index_jobs", "products", "categories")),
        "DELETE FROM users WHERE email LIKE '%@bench.shopsphere.test';",
        "SET FOREIGN_KEY_CHECKS = 1;",
    ]
    statements += batched_insert("categories", ["id", "category_name", "description", "image_url"], category_rows)
    statements += batched_insert(
        "products", ["id", "name", "image_url", "price", "price_cents", "description", "category_id", "stock"],
        product_rows)
    sql = "\n".join(statements) + "\n"

    graded: dict[str, dict[str, int]] = {}
    for label in labels:
        graded.setdefault(label["query_id"], {})[str(int(label["product_id"]) + 1)] = GAINS[label["label"]]
    order = sorted(queries, key=lambda q: int(q["query_id"]))
    random.Random(args.split_seed).shuffle(order)
    tune_count = round(len(order) * TUNE_SHARE)
    query_set = [{
        "query_id": int(q["query_id"]),
        "query": q["query"].strip(),
        "query_class": q.get("query_class") or "",
        "split": "tune" if n < tune_count else "heldout",
        "labels": graded.get(q["query_id"], {}),
    } for n, q in enumerate(order)]
    query_set.sort(key=lambda q: q["query_id"])

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "wands.sql").write_text(sql, encoding="utf-8")
    (args.out_dir / "queries.json").write_text(json.dumps(query_set, indent=1) + "\n", encoding="utf-8")
    manifest = {
        "dataset": "wands",
        "fixture_version": FIXTURE_VERSION,
        "source": "https://github.com/wayfair/WANDS (MIT)",
        "total_products": len(product_rows),
        "categories": len(category_rows),
        "queries": {"total": len(query_set), "tune": tune_count, "heldout": len(query_set) - tune_count,
                    "split_seed": args.split_seed},
        "labels": len(labels),
        "gains": GAINS,
        "price_rule": f"log-uniform {MIN_CENTS}-{MAX_CENTS} cents from sha256('wands-price:<wands id>')",
        "id_rule": "catalog id = WANDS product_id + 1",
        "sql_sha256": hashlib.sha256(sql.encode()).hexdigest(),
    }
    (args.out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"WANDS fixture v{FIXTURE_VERSION}: {manifest['total_products']} products, {manifest['categories']} "
          f"categories, {tune_count} tuning + {len(query_set) - tune_count} held-out queries, "
          f"sha256 {manifest['sql_sha256'][:12]}")


if __name__ == "__main__":
    main()
