-- Flyway V1: final Postgres schema. Table names match JPA @Table annotations.
-- Hibernate ddl-auto=validate checks these columns exist; it does not create them.
-- Single baseline: Neon is a new database, so V2/V3 history is not carried over.

CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    image_url VARCHAR(255) NOT NULL
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'USER',
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- Postgres VARCHAR compares case-sensitively; MySQL utf8mb4_0900_ai_ci did not.
CREATE UNIQUE INDEX uk_users_email_lower ON users (LOWER(email));
CREATE INDEX idx_user_email ON users (email);

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    description VARCHAR(255) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    category_id INTEGER NOT NULL,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE INDEX idx_product_category ON products (category_id);
CREATE INDEX idx_product_name ON products (name);

CREATE TABLE cart (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date TIMESTAMP(6),
    product_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT fk_cart_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT unique_cart_item UNIQUE (user_id, product_id)
);

CREATE INDEX idx_cart_user ON cart (user_id);

CREATE TABLE wishlist (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    created_date TIMESTAMP(6),
    product_id INTEGER,
    CONSTRAINT fk_wishlist_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    CONSTRAINT unique_wishlist_item UNIQUE (user_id, product_id)
);

CREATE INDEX idx_wishlist_user ON wishlist (user_id);

CREATE TABLE orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_date TIMESTAMP(6),
    total_price DOUBLE PRECISION,
    session_id VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    user_id INTEGER,
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_orders_session_id UNIQUE (session_id)
);

CREATE INDEX idx_order_user ON orders (user_id);

CREATE TABLE orderitems (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity INTEGER NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    created_date TIMESTAMP(6),
    order_id INTEGER,
    product_id INTEGER,
    CONSTRAINT fk_orderitems_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_orderitems_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
);

CREATE INDEX idx_order_item_order ON orderitems (order_id);

-- Hibernate 6 maps Instant to timestamptz; TIMESTAMP would fail ddl-auto=validate.
CREATE TABLE processed_stripe_events (
    event_id VARCHAR(255) NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (event_id)
);

